        <h2>1. Quem somos</h2>
        <p>A <strong>UTecnologia Saúde</strong> é uma plataforma SaaS de gestão clínica disponível em <a href="https://utecnologia.com.br">utecnologia.com.br</a>. Esta Política de Privacidade descreve como coletamos, usamos, armazenamos e protegemos os dados pessoais dos usuários do sistema, em conformidade com a <strong>Lei Geral de Proteção de Dados (LGPD — Lei nº 13.709/2018)</strong>.</p>
        <p>Ao utilizar a plataforma UTecnologia Saúde, você concorda com os termos desta Política.</p>

        <h2>2. Dados que coletamos</h2>
        <p>Coletamos dados pessoais nas seguintes situações:</p>
        <ul>
            <li><strong>Cadastro e acesso:</strong> nome, e-mail, telefone, senha (armazenada com hash seguro).</li>
            <li><strong>Dados de uso:</strong> endereço IP, navegador, páginas acessadas, data e hora dos acessos (analytics internos).</li>
            <li><strong>Dados inseridos pelos usuários do sistema:</strong> prontuários, fichas de pacientes, agendamentos e arquivos inseridos pelos responsáveis da clínica. Esses dados pertencem à clínica e são tratados como dados de saúde, sujeitos às exigências específicas da LGPD.</li>
        </ul>

        <div class="highlight-box">
            <p><strong>Importante:</strong> Os dados de pacientes inseridos no sistema (prontuários, exames, histórico clínico) são de responsabilidade da clínica ou profissional que os inseriu. A UTecnologia Saúde os armazena e protege, mas não os acessa para finalidades além da operação e suporte técnico do sistema.</p>
        </div>

        <h2>3. Como usamos os dados</h2>
        <p>Os dados coletados são utilizados para:</p>
        <ul>
            <li>Prestação dos serviços contratados (prontuário, agenda, gestão de pacientes);</li>
            <li>Autenticação e controle de acesso ao sistema;</li>
            <li>Suporte técnico e atendimento ao cliente;</li>
            <li>Comunicações sobre atualizações, manutenções e funcionalidades do sistema;</li>
            <li>Cumprimento de obrigações legais;</li>
            <li>Análise de uso para melhoria da plataforma (dados agregados e anonimizados).</li>
        </ul>
        <p>Não vendemos, alugamos nem compartilhamos dados pessoais com terceiros para fins comerciais.</p>

        <h2>4. Base legal para o tratamento</h2>
        <p>O tratamento de dados pela UTecnologia Saúde é realizado com base nas seguintes hipóteses previstas na LGPD (art. 7º e art. 11):</p>
        <ul>
            <li><strong>Execução de contrato:</strong> dados necessários para a prestação do serviço contratado.</li>
            <li><strong>Consentimento:</strong> para envio de comunicações de marketing (quando aplicável).</li>
            <li><strong>Legítimo interesse:</strong> para analytics interno de uso da plataforma.</li>
            <li><strong>Cumprimento de obrigação legal:</strong> quando exigido por lei.</li>
        </ul>

        <h2>5. Armazenamento e segurança</h2>
        <p>Os dados são armazenados em servidores localizados no Brasil. Adotamos medidas técnicas e organizacionais para proteger os dados contra acesso não autorizado, perda ou destruição, incluindo:</p>
        <ul>
            <li>Senhas armazenadas com hash seguro (bcrypt);</li>
            <li>Acesso ao sistema protegido por autenticação;</li>
            <li>Isolamento de dados por tenant (cada clínica em ambiente separado);</li>
            <li>Controle de acesso por perfil de usuário.</li>
        </ul>

        <h2>6. Compartilhamento com terceiros</h2>
        <p>A UTecnologia Saúde pode compartilhar dados com terceiros apenas nas seguintes situações:</p>
        <ul>
            <li><strong>Mercado Pago:</strong> para processamento de pagamentos de assinaturas (dados de faturamento).</li>
            <li><strong>Cumprimento legal:</strong> quando exigido por ordem judicial ou autoridade competente.</li>
        </ul>
        <p>Dados de prontuários e informações clínicas de pacientes <strong>não</strong> são compartilhados com terceiros, salvo por determinação legal.</p>

        <h2>7. Direitos dos titulares</h2>
        <p>Em conformidade com a LGPD, você tem direito a:</p>
        <ul>
            <li>Confirmar a existência de tratamento de seus dados;</li>
            <li>Acessar os dados que temos sobre você;</li>
            <li>Corrigir dados incompletos, inexatos ou desatualizados;</li>
            <li>Solicitar a anonimização, bloqueio ou eliminação de dados desnecessários;</li>
            <li>Revogar o consentimento a qualquer momento;</li>
            <li>Solicitar a portabilidade dos seus dados.</li>
        </ul>
        <p>Para exercer esses direitos, entre em contato pelo e-mail <a href="mailto:suporte@utecnologia.com.br">suporte@utecnologia.com.br</a>.</p>

        <h2>8. Cookies e rastreamento</h2>
        <p>O site utiliza cookies de sessão para manter o estado de autenticação. Utilizamos também o Google Analytics (GA4) para análise de tráfego de forma agregada e o Meta Pixel para mensuração de conversões de campanhas de marketing. Você pode desabilitar cookies no seu navegador, mas isso pode afetar o funcionamento do sistema.</p>

        <h2>9. Dados de menores</h2>
        <p>O sistema pode armazenar dados de pacientes menores de idade quando inseridos pelo responsável da clínica. Esses dados são tratados com a mesma proteção aplicada a todos os dados de saúde e exigem base legal adequada por parte do profissional responsável pelo atendimento.</p>

        <h2>10. Retenção de dados</h2>
        <p>Os dados são mantidos enquanto a conta da clínica estiver ativa. Após o cancelamento da assinatura, os dados são mantidos por até 90 dias para fins de eventual reativação. Após esse prazo, os dados são eliminados, salvo obrigação legal de retenção por prazo maior.</p>

        <h2>11. Alterações nesta Política</h2>
        <p>Esta Política pode ser atualizada periodicamente. Quando houver alterações relevantes, notificaremos os usuários ativos por e-mail. A data da última atualização está indicada no topo deste documento.</p>

